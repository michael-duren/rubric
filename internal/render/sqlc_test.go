func TestSQLCFilesAndCommands(t *testing.T) {
	c := testproject.Config()
	c.Features.Database, c.Features.Access = "postgres", "sqlc"
	files, err := render.Files(c, "new")
	if err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{"sqlc.yaml", "sql/queries.sql", "sql/schema.sql", "internal/store/queries/db.go"} {
		testproject.File(t, files, path)
	}
	facade := string(testproject.File(t, files, "internal/store/store.go"))
	if !strings.Contains(facade, "queries.New(db)") || strings.Contains(facade, "Code generated") {
		t.Fatalf("facade:\n%s", facade)
	}
	if !strings.HasPrefix(string(testproject.File(t, files, "internal/store/queries/queries.sql.go")), "// Code generated by sqlc. DO NOT EDIT.") {
		t.Fatal("bundled query code is not sqlc output")
	}
	normalized, err := render.Normalize(c, "new")
	if err != nil {
		t.Fatal(err)
	}
	i := slices.IndexFunc(normalized.Commands, func(cmd config.Command) bool { return cmd.Name == "generate" })
	if i < 0 || !slices.Equal(normalized.Commands[i].Argv, []string{"go", "run", sqlcLauncher, "generate"}) {
		t.Fatalf("commands = %+v", normalized.Commands)
	}
	if normalized.Generator.Tools["sqlc"] != "v1.31.1" {
		t.Fatalf("tools = %v", normalized.Generator.Tools)
	}
	c.Features.Access = "sql"
	plain, err := render.Normalize(c, "new")
	if err != nil {
		t.Fatal(err)
	}
	if slices.ContainsFunc(plain.Commands, func(cmd config.Command) bool { return cmd.Name == "generate" }) {
		t.Fatal("generate advertised without sqlc")
	}
}
