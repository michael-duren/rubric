const sqlcLauncher = "github.com/sqlc-dev/sqlc/cmd/sqlc@v1.31.1"

func TestSQLCRegenerationIsStable(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the pinned sqlc")
	}
	for _, backend := range []string{"sqlite", "postgres"} {
		t.Run(backend, func(t *testing.T) {
			c := testproject.Config()
			c.Features.Database, c.Features.Access = backend, "sqlc"
			files, err := render.Files(c, "new")
			if err != nil {
				t.Fatal(err)
			}
			root := testproject.Write(t, files)
			dir := filepath.Join(root, "internal", "store", "queries")
			before := readDir(t, dir)
			if before["db.go"] == nil || before["models.go"] == nil || before["queries.sql.go"] == nil {
				t.Fatalf("bundled query files = %v", slices.Collect(mapsKeys(before)))
			}
			testproject.Go(t, root, "run", sqlcLauncher, "generate")
			after := readDir(t, dir)
			if len(after) != len(before) {
				t.Fatalf("regeneration changed the file set: %v", slices.Collect(mapsKeys(after)))
			}
			for name, data := range before {
				if !bytes.Equal(data, after[name]) {
					t.Fatalf("sqlc output drifted in %s", name)
				}
			}
		})
	}
}

func readDir(t *testing.T, dir string) map[string][]byte {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	out := map[string][]byte{}
	for _, e := range entries {
		data, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		out[e.Name()] = data
	}
	return out
}

func mapsKeys(m map[string][]byte) func(func(string) bool) {
	return func(yield func(string) bool) {
		for k := range m {
			if !yield(k) {
				return
			}
		}
	}
}

