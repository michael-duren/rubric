const templLauncher = "github.com/a-h/templ/cmd/templ@v0.3.1020"

func webConfig(router, e2e string) config.Config {
	c := testproject.Config()
	c.Features.HTTP, c.Features.Web, c.Features.E2E = router, "htmx", e2e
	return c
}

func TestGeneratedWebFiles(t *testing.T) {
	files, err := render.Files(webConfig("chi", "playwright"), "new")
	if err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{
		"internal/web/views.templ", "internal/web/web.go", "internal/web/web_test.go",
		"internal/web/static/htmx.min.js", "internal/web/static/alpine.min.js", "internal/web/static/THIRD_PARTY_LICENSES.md",
		"e2e/ui_test.go",
	} {
		testproject.File(t, files, path)
	}
	views := testproject.File(t, files, "internal/web/views_templ.go")
	if !bytes.HasPrefix(views, []byte("// Code generated by templ - DO NOT EDIT.")) {
		t.Fatal("bundled views are not templ output")
	}
	if !bytes.Contains(testproject.File(t, files, "internal/web/static/alpine.min.js"), []byte("{{")) {
		t.Fatal("Alpine bundle was altered by template rendering")
	}
	if !strings.HasPrefix(string(testproject.File(t, files, "e2e/ui_test.go")), "//go:build e2e") {
		t.Fatal("browser tests are not behind the e2e build tag")
	}
	routes := string(testproject.File(t, files, "internal/httpserver/routes.go"))
	if !strings.Contains(routes, `"example.com/demo/internal/web"`) {
		t.Fatalf("router does not mount the web UI:\n%s", routes)
	}
	normalized, err := render.Normalize(webConfig("chi", "playwright"), "new")
	if err != nil {
		t.Fatal(err)
	}
	names := commandNames(normalized.Commands)
	for _, want := range []string{"generate-templ", "setup-e2e", "test-e2e"} {
		if !slices.Contains(names, want) {
			t.Fatalf("commands = %v", names)
		}
	}
	agents := string(testproject.File(t, files, "AGENTS.md"))
	for _, want := range []string{"htmx", "Alpine.js", "templ", "Playwright", "`internal/web`", "`e2e`", "-tags e2e"} {
		if !strings.Contains(agents, want) {
			t.Errorf("guidance missing %q", want)
		}
	}
	plain, err := render.Files(webConfig("nethttp", "none"), "new")
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := find(plain, "e2e/ui_test.go"); ok {
		t.Fatal("browser tests generated without Playwright")
	}
	if strings.Contains(string(testproject.File(t, plain, "AGENTS.md")), "Playwright") {
		t.Fatal("guidance mentions Playwright when it is not selected")
	}
}

func TestExistingWebGuidanceMentionsOnlyAvailableCommands(t *testing.T) {
	c := webConfig("chi", "playwright")
	c.Project.Go = "1.22"
	files, err := render.Files(c, "existing")
	if err != nil {
		t.Fatal(err)
	}
	agents := string(testproject.File(t, files, "AGENTS.md"))
	for _, bad := range []string{"`e2e`", "setup-e2e", "test-e2e", "generate-templ"} {
		if strings.Contains(agents, bad) {
			t.Errorf("existing-mode guidance mentions undefined %s:\n%s", bad, agents)
		}
	}
}

