func TestGeneratedWeb(t *testing.T) {
	if testing.Short() {
		t.Skip("builds generated projects")
	}
	webTests := []string{"TestPageEscapesTitle", "TestPageLoadsAssets", "TestIncrement", "TestConcurrentIncrements",
		"TestStaticAssets", "TestRenderFailure", "TestIncrementRejectsCrossOrigin", "TestWebRoutes", "TestHealth"}
	for _, tt := range []struct {
		name string
		f    config.Features
	}{
		{"nethttp", features(func(f *config.Features) { f.HTTP, f.Web = "nethttp", "htmx" })},
		{"chi playwright sqlite", features(func(f *config.Features) {
			f.HTTP, f.Web, f.E2E, f.Database, f.Access, f.CLI = "chi", "htmx", "playwright", "sqlite", "sql", "flag"
		})},
	} {
		t.Run(tt.name, func(t *testing.T) {
			c := testproject.Config()
			c.Features = tt.f
			files, err := render.Files(c, "new")
			if err != nil {
				t.Fatal(err)
			}
			root := testproject.Write(t, files)
			testproject.Go(t, root, "mod", "tidy")
			testproject.Go(t, root, "vet", "-tags", "e2e", "./...")
			out := testproject.Go(t, root, "test", "-count=1", "-race", "-v", "./...")
			for _, name := range webTests {
				if !strings.Contains(out, "--- PASS: "+name) {
					t.Errorf("generated test %s did not pass:\n%s", name, out)
				}
			}
		})
	}
}

func TestTemplRegenerationIsStable(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the pinned templ")
	}
	files, err := render.Files(webConfig("nethttp", "none"), "new")
	if err != nil {
		t.Fatal(err)
	}
	root := testproject.Write(t, files)
	before := testproject.File(t, files, "internal/web/views_templ.go")
	testproject.Go(t, root, "run", templLauncher, "generate")
	after, err := os.ReadFile(filepath.Join(root, "internal", "web", "views_templ.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(before, after) {
		t.Fatal("templ output drifted")
	}
}
